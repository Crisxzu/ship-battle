package com.par_28.ship_battle.model.enums;

/**
 * Enum representing the different states of the game.
 */
public enum GameState {
    /**
     * Game setup phase.
     */
    SETUP,
    /**
     * Player 1's turn to attack.
     */
    PLAYER1_TURN,
    /**
     * Player 2's turn to attack.
     */
    PLAYER2_TURN,
    /**
     * Game over state.
     */
    GAME_OVER
}
